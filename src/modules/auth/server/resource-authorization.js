export function permissionFor(action, resource) {
  return RESOURCE_PERMISSIONS[resource]?.[action] || null;
}

export function canResource(user, action, resource) {
  const permission = permissionFor(action, resource);
  if (!permission) return false;
  return hasPermission(user?.permissions, permission);
}
